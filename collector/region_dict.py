def build_lookup():
    """构建关键词 → 地区 的查找表（keyword 原文 → region tuple）。"""
    table = {}
    for keywords, name, lon, lat, iso in REGIONS:
        for kw in keywords:
            table[kw] = (name, lon, lat, iso)
    return table


LOOKUP = build_lookup()


def match_region(text, default_region=None):
    """在文本中查找命中的地区。

    返回 [(地区名, 经度, 纬度, iso3, 命中的关键词), ...]
    按关键词长度降序匹配（更长更精确的词优先）。
    若 text 未命中任何关键词 → 返回默认地区。
    """
    if not text:
        return [(DEFAULT_REGION[0], DEFAULT_REGION[1], DEFAULT_REGION[2],
                 DEFAULT_REGION[3], "")]

    hits = []
    seen = set()
    for kw in sorted(LOOKUP, key=len, reverse=True):
        if kw in text and kw not in seen:
            name, lon, lat, iso = LOOKUP[kw]
            hits.append((name, lon, lat, iso, kw))
            seen.add(kw)
        if len(hits) >= 5:
            break

    if not hits:
        name, lon, lat, iso = default_region or DEFAULT_REGION
        return [(name, lon, lat, iso, "")]

    # 去重（同一地区只保留一个命中，取更长的关键词）
    dedup = {}
    for h in hits:
        key = h[0]
        if key not in dedup or len(h[4]) > len(dedup[key][4]):
            dedup[key] = h
    return list(dedup.values())


def is_domestic(region_names):
    """判断命中的地区是否均为中国境内。"""
    cn_iso = {"CHN"}
    if not region_names:
        return True
    # 若所有命中地区 iso 都在中国集合（或空），视为国内
    return all(r[3] in cn_iso or r[3] == "" for r in region_names)
